import { gzipSync } from 'node:zlib';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const dist = resolve(root, 'build/web');
let html = await readFile(resolve(dist, 'index.html'), 'utf8');
const css = await readFile(resolve(dist, 'app.css'), 'utf8');
const javascript = await readFile(resolve(dist, 'app.js'), 'utf8');
// Vite minifies scripts and styles but preserves template indentation. Remove
// whitespace between HTML tags before embedding to protect the flash budget.
html = html
  .replace(/>\s+</g, '><')
  // HTML void elements do not need XHTML-style closing slashes. Removing them
  // here keeps source readable while saving a few embedded-flash bytes.
  .replace(/\s*\/>/g, '>')
  // Quotes are optional around these conservative, whitespace-free HTML
  // attribute values. Leave paths, data URLs and prose attributes untouched.
  .replace(/="([A-Za-z0-9._:-]+)"/g, '=$1')
  .trim()
  // Vite may reorder attributes between versions, so match the fixed asset name
  // instead of depending on a particular serialization of the element.
  .replace(/<link[^>]*app\.css[^>]*>/, () => `<style>${css}</style>`)
  .replace(/<script[^>]*app\.js[^>]*>/, () => `<script type="module">${javascript}`);
const remainingAssetTag = html.match(/<(?:link|script)[^>]*(?:app\.css|app\.js)[^>]*>/)?.[0];
if (remainingAssetTag) {
  throw new Error(`Vite asset inlining failed: ${remainingAssetTag}`);
}
const compressed = gzipSync(Buffer.from(html), { level: 9, mtime: 0 });
// zlib writes a platform-specific operating-system value into gzip byte 9
// (Windows 10, Unix 3). It has no effect on decompression, but normalizing it
// makes the committed firmware asset byte-for-byte reproducible in local
// Windows builds and Linux CI.
compressed[9] = 255;
await writeFile(resolve(dist, 'index.html.gz'), compressed);
const rows = [];
for (let i = 0; i < compressed.length; i += 12) {
  rows.push('    ' + [...compressed.subarray(i, i + 12)].map(value => `0x${value.toString(16).padStart(2, '0')}`).join(', '));
}
const header = `#pragma once

// Generated by tools/embed-web.mjs from the minified Vite build.
// Do not edit this byte array by hand.
static const uint8_t WEB_INDEX_GZIP[] PROGMEM = {
${rows.join(',\n')}
};
static const size_t WEB_INDEX_GZIP_LENGTH = sizeof(WEB_INDEX_GZIP);
`;
await writeFile(resolve(root, 'firmware/AdvatekTrigger/src/web/WebAsset.h'), header);
console.log(`Embedded ${html.length} bytes of HTML as ${compressed.length} gzipped bytes.`);
